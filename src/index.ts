server.registerTool(
  "start_guide",
  {
    title: "Start a user guide session",
    description:
      'Call this first when the user asks to "generate the user guide" or "create the user guide" for a Jira issue (key, link, or number). ' +
      "Creates (or resets) the working session for the issue: an image store and an inbox folder where the user can drop Jira screenshots. Then read the issue with the Atlassian MCP.",
    inputSchema: {
      issue: z.string().describe("Jira issue key (KAN-20) or browse URL."),
      summary: z.string().optional().describe("Issue summary, if already known."),
      reset: z.boolean().default(true).describe("Discard images and sources from an earlier session for this issue."),
    },
  },
  async ({ issue, summary, reset }) => {
    try {
      const refused = clientCheck();
      if (refused) return fail(refused);
      const key = keyOf(issue);
      if (reset) {
        // Clear the earlier session but keep the inbox, so screenshots saved in advance are not lost.
        const dir = issueWorkDir(key);
        const entries = await fs.readdir(dir).catch(() => [] as string[]);
        for (const name of entries) if (name !== "inbox") await fs.rm(path.join(dir, name), { recursive: true, force: true });
      }
      let bundle;
      try {
        bundle = reset ? emptyBundle(key, summary) : await loadBundle(key);
      } catch {
        bundle = emptyBundle(key, summary);
      }
      if (summary) bundle.rootTitle = summary;
      await fs.mkdir(inboxDir(key), { recursive: true });
      await saveBundle(bundle);
      const importedFromInbox = await autoImportInbox(bundle);
      return json({
        issueKey: key,
        jiraSite: config.atlassian.baseUrl
          ? new URL(config.atlassian.baseUrl).host
          : "Not set. Take the host from the link the user gave, or call getAccessibleAtlassianResources.",
        inboxFolder: inboxDir(key),
        importedFromInbox,
        attachmentDownloads: config.atlassian.token
          ? "ATLASSIAN_API_TOKEN is set: pass Jira attachment content URLs to add_image."
          : "No Atlassian token: ask the user to save Jira image attachments into inboxFolder, then call import_images.",
        contactDefaults: config.defaults,
        workflow: MCP_WORKFLOW,
        writingRules: AUTHORING_GUIDE,
      });
    } catch (e) {
      return fail((e as Error).message);
    }
  },
);

server.registerTool(
  "register_source",
  {
    title: "Register a source",
    description:
      "Records a Jira issue, Confluence page, or Figma design you read through another MCP server, with its full text. The guide is checked against these texts: anything not supported by a registered source is rejected as out of scope.",
    inputSchema: {
      issueKey: z.string(),
      id: z.string().describe("Stable id: jira:KAN-21, confluence:12345, figma:<fileKey> or figma:<fileKey>:<node>."),
      kind: z.enum(KINDS),
      title: z.string(),
      url: z.string().default(""),
      notes: z.string().optional().describe("One line on what this source contributes (features, rules, screens)."),
      content: z
        .string()
        .min(1)
        .describe(
          "The text exactly as the Atlassian or Figma MCP tools returned it in this conversation. Never sample, test, reconstructed or summarised text. Include: summary, description, acceptance criteria, other fields and comments for an issue; the page body for Confluence; screen names, visible text and prototype links for Figma. The guide is checked against this text, so do not shorten or paraphrase it.",
        ),
    },
  },
  async ({ issueKey, id, kind, title, url, notes, content }) => {
    try {
      const refused = clientCheck();
      if (refused) return fail(refused);
      const b = await loadBundle(keyOf(issueKey));
      const existing = b.sources.find((s) => s.id === id);
      const imageIds = b.images.filter((i) => i.sourceId === id).map((i) => i.id);
      if (existing) Object.assign(existing, { kind: kind as SourceKind, title, url, notes, text: content, imageIds: [...new Set([...existing.imageIds, ...imageIds])] });
      else b.sources.push({ id, kind: kind as SourceKind, title, url, text: content, notes, imageIds });
      if (kind === "jira-issue" && !b.rootTitle) b.rootTitle = title;
      await saveBundle(b);
      return json({ registered: id, characters: content.length, sources: b.sources.length });
    } catch (e) {
      return fail((e as Error).message);
    }
  },
);

