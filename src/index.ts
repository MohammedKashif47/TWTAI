server.registerTool(
  "build_user_guide",
  {
    title: "Build the Word user guide",
    description:
      "Checks the guide spec against the registered source texts (every feature, detail section, procedure and troubleshooting entry needs word-for-word evidence; topics, terms, labels and numbers not found in the sources are rejected or flagged), reports how much of the source content the guide explains, checks MSTP style, then writes a .docx with a title page, table of contents, introduction, one section per feature (overview, navigation from the home screen, details, screen elements, procedures, screenshots with figure captions), and an appendix. Pass the spec inline or as specPath to a JSON file.",
    inputSchema: {
      issueKey: z.string().describe("Root issue key used with collect_guide_sources."),
      spec: GuideSpecSchema.optional().describe("The full guide spec."),
      specPath: z.string().optional().describe("Path to a JSON file holding the spec (use for long guides)."),
      outputDir: z.string().optional().describe(`Folder for the .docx. Defaults to ${config.outputDir}.`),
      ignoreWarnings: z.boolean().default(true).describe("Build even when style warnings remain (errors always block)."),
      dryRun: z.boolean().default(false).describe("Only check the spec (scope, evidence, coverage, style) without writing the .docx."),
    },
  },
  async ({ issueKey, spec, specPath, outputDir, ignoreWarnings, dryRun }) => {
    try {
      const refused = clientCheck();
      if (refused) return fail(refused);
      const key = keyOf(issueKey);
      const bundle = await loadBundle(key);
      const newFromInbox = await autoImportInbox(bundle);

      let parsed: GuideSpec;
      if (spec) parsed = GuideSpecSchema.parse(spec);
      else if (specPath) parsed = GuideSpecSchema.parse(JSON.parse(await fs.readFile(path.resolve(specPath), "utf8")));
      else return fail("Provide either spec or specPath.");

      const lint = lintSpec(parsed, new Set(bundle.images.map((i) => i.id)));
      const knownSources = new Set(bundle.sources.map((s) => s.id));
      for (const f of parsed.features) {
        const unknown = (f.sourceIds ?? []).filter((id) => !knownSources.has(id));
        if (unknown.length) lint.warnings.push(`"${f.title}" cites unregistered sources: ${unknown.join(", ")}.`);
      }
      // List the specs and designs the guide was written from when the spec has no references of its own.
      if (!parsed.appendix.references?.length) {
        const refs = bundle.sources.filter((s) => s.kind === "confluence" || s.kind === "figma").map((s) => ({ title: s.title, url: s.url || undefined }));
        if (refs.length) parsed.appendix.references = refs;
      }
      const ground = checkGrounding(parsed, bundle);

      // Every collected screenshot must be placed in the guide, or excluded on purpose with a reason.
      const placed = new Set<string>();
      JSON.stringify(parsed).replace(/"(?:imageId|overviewImageId)":"([^"]+)"/g, (_m, id) => (placed.add(id), ""));
      const excluded = new Set((parsed.excludedImages ?? []).map((e) => e.imageId));
      const notPlaced = bundle.images.filter((i) => !placed.has(i.id) && !excluded.has(i.id));
      if (notPlaced.length) {
        ground.errors.push(
          `${notPlaced.length} collected screenshot(s) are not in the guide: ${notPlaced.map((i) => `${i.id} "${i.label}" (${i.originalName})`).join(", ")}. ` +
            "Look at each one with view_image, record its text with record_image_text, and place it at the step or section that shows that screen " +
            "(navigation step imageId, procedure step imageId, details imageId, or the feature's images list). Only if it really shows nothing the guide covers, list it in excludedImages with a reason.",
        );
      }
      const unread = bundle.images.filter((i) => !i.visibleText && !excluded.has(i.id));
      if (unread.length) {
        ground.warnings.push(`No text recorded for ${unread.map((i) => i.id).join(", ")}. Call view_image and record_image_text for each, so their labels can be used and checked.`);
      }
      lint.errors.push(...ground.errors);
      lint.warnings.unshift(...ground.warnings);
      const coverage = {
        ...ground.coverage,
        howToUse:
          "Each uncovered item is a statement from the sources that the guide does not explain yet. Explain every user-relevant one in full (what it is, where it appears, when and why the user needs it, what happens, and its rules or limits) in the matching feature section. Skip only developer notes, test tasks and status updates.",
      };
      if (lint.errors.length || (!ignoreWarnings && lint.warnings.length)) {
        return json({
          built: false,
          errors: lint.errors,
          warnings: lint.warnings,
          coverage,
          newImagesFromInbox: newFromInbox,
          fix: "Remove out-of-scope content, add evidence quotes copied from the sources, and call build_user_guide again.",
        });
      }
      if (dryRun) return json({ built: false, dryRun: true, ok: true, warnings: lint.warnings, coverage, newImagesFromInbox: newFromInbox });

      const dir = path.resolve(outputDir || config.outputDir);
      await fs.mkdir(dir, { recursive: true });
      const base =
        (parsed.outputFileName?.replace(/\.docx$/i, "") ||
          parsed.title.replace(/[^\w\s-]/g, "").trim().replace(/\s+/g, "-")).slice(0, 100) || "User-Guide";
      let outFile = path.join(dir, `${base}.docx`);
      try {
        await fs.access(outFile);
        // Keep earlier builds; a file open in Word cannot be overwritten anyway.
        const stamp = new Date().toISOString().replace(/[-:]/g, "").slice(0, 15);
        outFile = path.join(dir, `${base}-${stamp}.docx`);
      } catch {
        /* file does not exist yet */
      }

      await fs.writeFile(path.join(issueWorkDir(key), "guide-spec.json"), JSON.stringify(parsed, null, 2), "utf8");
      const company = parsed.companyName || config.defaults.companyName;
      const stats = await buildDocx(parsed, bundle.images, outFile, company);

      const unused = (parsed.excludedImages ?? []).map((e) => `${e.imageId}: ${e.reason}`);

      return json({
        built: true,
        file: outFile,
        title: parsed.title,
        features: parsed.features.length,
        figures: stats.figures,
        excludedImages: unused,
        warnings: lint.warnings,
        coverage,
        tip: "Word fills in the table of contents page numbers when the document opens (accept the prompt to update fields).",
      });
    } catch (e) {
      if (e instanceof z.ZodError) return fail(`The spec is not valid:\n${JSON.stringify(e.issues, null, 2)}`);
      return fail(`Build failed: ${(e as Error).message}`);
    }
  },
);

/* ---------------- Prompt: the whole workflow in one command ---------------- */
function guidePrompt(issue: string, audience?: string): string {
  const intro = `Create a complete end-user guide in Word format from the Jira issue ${issue}.\n\n` + (audience ? `Intended audience: ${audience}.\n\n` : "");
  if (MODE === "mcp") return `${intro}${MCP_WORKFLOW}\n\n${AUTHORING_GUIDE}`;
  return (
    intro +
    `1. Call collect_guide_sources with issue "${issue}".\n2. Read every source with read_source (page through long ones).\n` +
    "3. Look at every image with view_image and record its text with record_image_text. Write the guide spec.\n" +
    "4. Call build_user_guide with dryRun until there are no errors and full coverage, then build it and report the file path.\n\n" +
    AUTHORING_GUIDE
  );
}

