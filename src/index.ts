const log = (msg: string) => console.error(`[user-guide-mcp] ${msg}`);
const json = (v: unknown) => ({ content: [{ type: "text" as const, text: JSON.stringify(v, null, 2) }] });
const fail = (msg: string) => ({ isError: true, content: [{ type: "text" as const, text: msg }] });

function keyOf(input: string): string {
  const key = parseJiraKey(input);
  if (!key) {
    throw new Error(
      `Could not find a Jira issue in "${input}". Use a key such as KAN-20 or a Jira link` +
        (config.defaultProjectKey ? "." : ", or set JIRA_PROJECT_KEY in .env to allow bare issue numbers."),
    );
  }
  return key;
}

/**
 * Guides must be generated from a real MCP client (Claude Code, Claude Desktop, VS Code, ...),
 * where the Atlassian and Figma MCP tools supply the source text. Scripts that start this server
 * themselves have no access to Jira and end up feeding it invented text, so they are refused.
 * Set ALLOWED_MCP_CLIENTS=* (or a comma-separated list of client names) to override.
 */
const KNOWN_CLIENTS = /claude|vscode|visual studio code|copilot|cursor|windsurf|inspector|zed|cline|continue/i;
function clientCheck(): string | null {
  const name = server.server.getClientVersion()?.name ?? "";
  const allowed = (process.env.ALLOWED_MCP_CLIENTS ?? "").split(",").map((x) => x.trim()).filter(Boolean);
  if (allowed.includes("*") || allowed.includes(name) || KNOWN_CLIENTS.test(name)) return null;
  return (
    `This server was started by "${name || "an unknown client"}", which looks like a script rather than Claude Code or another MCP client. ` +
    "User guides must be generated by calling these tools directly in the Claude conversation, with source text from the Atlassian and Figma MCP tools. " +
    "Do not write scripts that start this server, and do not use the test data in scripts/. If the tools are not available in the conversation, tell the user to check /mcp."
  );
}

/** Imports any images in the session inbox that are not collected yet. They are attributed to the root issue. */
async function autoImportInbox(bundle: SourceBundle): Promise<string[]> {
  try {
    const r = await importFolder(bundle, undefined, `jira:${bundle.issueKey}`);
    return r.added.map((i) => `${i.id} (${i.originalName})`);
  } catch {
    return [];
  }
}

